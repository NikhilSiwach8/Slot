"""Cut the moving parts out of the bonus splash art (art/source/fs_*.webp) so the game can
animate them: each layer is its box from art/splash_layers.json with a feathered
rounded edge (so small moves blend into the identical art underneath).

Writes static/assets/sprites/dukeSplashLayers/<splash>_<id>.webp and the geometry the
client needs to web-sdk/apps/dumpster-duke/src/game/splashLayers.ts.

Usage: python art/make_splash_layers.py
"""
import json
import os

import numpy as np
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "..", "web-sdk", "apps", "dumpster-duke")
OUT = os.path.join(APP, "static", "assets", "sprites", "dukeSplashLayers")
TS = os.path.join(APP, "src", "game", "splashLayers.ts")
ART_W, ART_H = 1024, 1536


def feather_mask(w, h, edge):
    x = np.minimum(np.arange(w), np.arange(w)[::-1]) / edge
    y = np.minimum(np.arange(h), np.arange(h)[::-1]) / edge
    ramp = np.clip(np.minimum(x[None, :], y[:, None]), 0, 1)
    ramp = ramp * ramp * (3 - 2 * ramp)  # smoothstep
    return Image.fromarray((ramp * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(edge * 0.15))


def main():
    spec = json.load(open(os.path.join(HERE, "splash_layers.json")))
    os.makedirs(OUT, exist_ok=True)
    geometry = {}
    for name, layers in spec.items():
        art = Image.open(os.path.join(HERE, "source", f"fs_{name}.webp")).convert("RGB")
        assert art.size == (ART_W, ART_H), art.size
        geometry[name] = []
        for layer in layers:
            x0, y0, x1, y1 = layer["box"]
            crop = art.crop((x0, y0, x1, y1)).convert("RGBA")
            crop.putalpha(feather_mask(x1 - x0, y1 - y0, max(8, min(x1 - x0, y1 - y0) * 0.12)))
            key = f"{name}_{layer['id']}"
            crop.save(os.path.join(OUT, f"{key}.webp"), quality=86)
            geometry[name].append({
                "key": f"splash_{key}",
                "file": f"{key}.webp",
                # all in fractions of the 2:3 art
                "x": (x0 + x1) / 2 / ART_W, "y": (y0 + y1) / 2 / ART_H,
                "w": (x1 - x0) / ART_W, "h": (y1 - y0) / ART_H,
                "px": layer["pivot"][0] / ART_W, "py": layer["pivot"][1] / ART_H,
                "anim": layer["anim"],
            })
            print(key, crop.size, os.path.getsize(os.path.join(OUT, f"{key}.webp")) // 1024, "KB")
    with open(TS, "w") as f:
        f.write("// Generated by art/make_splash_layers.py. Moving parts of the bonus splashes, in\n")
        f.write("// fractions of the 2:3 art: centre (x, y), size (w, h), pivot (px, py), animation.\n")
        f.write("export const SPLASH_LAYERS = " + json.dumps(geometry, indent="\t") + " as const;\n\n")
        # one static new URL(...) per file: Vite only bundles literal asset paths
        f.write("export const splashLayerAssets = {\n")
        for layers in geometry.values():
            for layer in layers:
                f.write(f"\t{layer['key']}: {{\n\t\ttype: 'sprite' as const,\n")
                f.write(f"\t\tsrc: new URL('../../assets/sprites/dukeSplashLayers/{layer['file']}', import.meta.url).href,\n")
                f.write("\t\tpreload: false,\n\t},\n")
        f.write("};\n")

if __name__ == "__main__":
    main()
