"""Cut the moving parts out of the game backgrounds (lanterns, crystals, the gold cart,
the tunnel's glowing exit) so the client can loop small animations on them. Boxes are in
art/bg_layers.json per orientation; every background variant (base, raid) is cut with the
same boxes. Feathered edges (shared with make_splash_layers.py) blend each part into the
identical art underneath.

Writes static/assets/sprites/dukeBgLayers/bg_<variant>_<orientation>_<id>.webp and
web-sdk/apps/dumpster-duke/src/game/bgLayers.ts.

Usage: python art/make_bg_layers.py
"""
import json
import os

from PIL import Image

from make_splash_layers import APP, feather_mask

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(APP, "static", "assets", "sprites", "dukeBackgrounds")
OUT = os.path.join(APP, "static", "assets", "sprites", "dukeBgLayers")
TS = os.path.join(APP, "src", "game", "bgLayers.ts")
VARIANTS = ["base", "raid"]


def main():
    spec = json.load(open(os.path.join(HERE, "bg_layers.json")))
    os.makedirs(OUT, exist_ok=True)
    geometry, assets = {}, []
    for orientation, layers in spec.items():
        geometry[orientation] = []
        for variant in VARIANTS:
            image = Image.open(os.path.join(SRC, f"bg_{variant}_{orientation}.webp")).convert("RGB")
            W, H = image.size
            for layer in layers:
                x0, y0, x1, y1 = layer["box"]
                crop = image.crop((x0, y0, x1, y1)).convert("RGBA")
                crop.putalpha(feather_mask(x1 - x0, y1 - y0, max(6, min(x1 - x0, y1 - y0) * 0.14)))
                name = f"bg_{variant}_{orientation}_{layer['id']}"
                crop.save(os.path.join(OUT, f"{name}.webp"), quality=86)
                assets.append(name)
                if variant == VARIANTS[0]:
                    geometry[orientation].append({
                        "id": layer["id"],
                        # fractions of the background image
                        "x": (x0 + x1) / 2 / W, "y": (y0 + y1) / 2 / H,
                        "w": (x1 - x0) / W, "h": (y1 - y0) / H,
                        "px": layer["pivot"][0] / W, "py": layer["pivot"][1] / H,
                        "anim": layer["anim"],
                    })
    with open(TS, "w") as f:
        f.write("// Generated by art/make_bg_layers.py. Moving parts of the backgrounds, in fractions of\n")
        f.write("// the background image: centre (x, y), size (w, h), pivot (px, py), animation. The\n")
        f.write("// sprite key is `bg_<variant>_<orientation>_<id>` (variants: base, raid).\n")
        f.write("export const BG_LAYERS = " + json.dumps(geometry, indent="\t") + " as const;\n\n")
        f.write("// one static new URL(...) per file: Vite only bundles literal asset paths\n")
        f.write("export const bgLayerAssets = {\n")
        for name in assets:
            f.write(f"\t{name}: {{\n\t\ttype: 'sprite' as const,\n")
            f.write(f"\t\tsrc: new URL('../../assets/sprites/dukeBgLayers/{name}.webp', import.meta.url).href,\n")
            f.write("\t\tpreload: true,\n\t},\n")
        f.write("};\n")
    total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
    print(len(assets), "layers,", total // 1024, "KB")


if __name__ == "__main__":
    main()
