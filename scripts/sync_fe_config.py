"""Copy the math SDK's frontend config into the game client.

Reads  math/dumpster_duke/library/configs/config_fe_dumpster_duke.json
Writes web-sdk/apps/dumpster-duke/src/game/config.ts
Run with the math-sdk venv after every math run so paytables, reels and bet modes stay in sync.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "math", "dumpster_duke", "library", "configs", "config_fe_dumpster_duke.json")
DST = os.path.join(ROOT, "web-sdk", "apps", "dumpster-duke", "src", "game", "config.ts")

with open(SRC) as f:
    config = json.load(f)

# Newer math-sdk versions emit symbols as a list of single-key objects; the client
# template indexes them by name, so merge into one object.
if isinstance(config.get("symbols"), list):
    config["symbols"] = {k: v for item in config["symbols"] for k, v in item.items()}
# Rule values that the math SDK's frontend export leaves out (free-spin awards, cap
# values) are read straight from the game config so the rules screen can't drift.
MATH_SDK = os.environ.get("MATH_SDK", os.path.join(ROOT, "math-sdk"))
sys.path[:0] = [MATH_SDK, os.path.join(ROOT, "math", "dumpster_duke")]
os.chdir(MATH_SDK)
from game_config import GameConfig  # noqa: E402

gc = GameConfig()
config["dukeRules"] = {
    "minCluster": min(n for n, _ in gc.paytable),
    "scatterAwards": [{"scatters": k, "spins": v} for k, v in sorted(gc.freespin_triggers[gc.basegame_type].items())],
    "retrigger": [{"scatters": k, "spins": v} for k, v in sorted(gc.freespin_triggers[gc.freegame_type].items())],
    "capValues": gc.cap_values,
}

with open(DST, "w") as f:
    f.write("// Generated by scripts/sync_fe_config.py from the math SDK output. Do not edit by hand.\n")
    f.write("export default " + json.dumps(config, indent="\t") + ";\n")
print(f"wrote {DST} ({len(config.get('symbols', {}))} symbols, modes: {list(config.get('betModes', {}))})")
