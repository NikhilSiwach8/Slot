"""Pick representative simulated rounds from the math output for Storybook replays.

Writes web-sdk/apps/dumpster-duke/src/stories/data/{base,bonus}_books.ts.
Run with the math-sdk venv (needs zstandard):
    math-sdk/env/bin/python scripts/make_story_books.py [mode ...]   (default: every mode in PLAN)
"""
import io
import json
import os
import random
import sys

import zstandard

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLISH = os.path.join(ROOT, "math", "dumpster_duke", "library", "publish_files")
OUT = os.path.join(ROOT, "web-sdk", "apps", "dumpster-duke", "src", "stories", "data")

# (min payout, max payout, how many) per mode — a spread from small wins to huge ones
PLAN = {
    "base": [(0, 0, 4), (0.01, 2, 8), (2, 20, 8), (20, 200, 6), (200, 1e9, 6)],
    "bonus": [(0, 50, 3), (50, 200, 6), (200, 1000, 6), (1000, 1e9, 5)],
    "feature": [(0, 0, 2), (0.01, 20, 3), (50, 1e9, 3)],
    "super": [(0, 300, 2), (300, 1e9, 2)],
    "mystery": [(0, 100, 2), (100, 1e9, 2)],
}


def stream(mode):
    """Yield (index, raw line) without holding every book in memory."""
    with open(os.path.join(PUBLISH, f"books_{mode}.jsonl.zst"), "rb") as f:
        reader = io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(f), encoding="utf-8")
        for i, line in enumerate(reader):
            if line.strip():
                yield i, line


def main():
    rng = random.Random(7)
    modes = sys.argv[1:] or list(PLAN)
    for mode, plan in ((m, PLAN[m]) for m in modes):
        # pass 1: lightweight summary of every book
        summary = []
        for i, line in stream(mode):
            book = json.loads(line)
            types = {e["type"] for e in book["events"]}
            summary.append((i, book["payoutMultiplier"] / 100, "boardMultiplierInfo" in types, "freeSpinTrigger" in types))
        chosen = set()
        for lo, hi, n in plan:
            pool = [b for b in summary if lo <= b[1] <= hi]
            # prefer rounds that show the features (caps applied, bonus triggered)
            pool.sort(key=lambda b: (b[2], b[3]), reverse=True)
            chosen.update(b[0] for b in rng.sample(pool[: max(n * 5, n)], min(n, len(pool))))
        # pass 2: keep only the chosen books
        picked = [json.loads(line) for i, line in stream(mode) if i in chosen]
        with open(os.path.join(OUT, f"{mode}_books.ts"), "w") as f:
            f.write("// Generated by scripts/make_story_books.py from the math output.\n")
            f.write("export default " + json.dumps(picked, indent="\t") + ";\n")
        # one example of every event type (from the richest picked rounds) for the
        # per-event stories
        examples = {}
        for book in sorted(picked, key=lambda b: -len(b["events"])):
            for event in book["events"]:
                examples.setdefault(event["type"], event)
        with open(os.path.join(OUT, f"{mode}_events.ts"), "w") as f:
            f.write("// Generated by scripts/make_story_books.py from the math output.\n")
            f.write("export default " + json.dumps(examples, indent="\t") + ";\n")
        print(mode, len(picked), "books", sorted(b["payoutMultiplier"] / 100 for b in picked))


if __name__ == "__main__":
    main()
