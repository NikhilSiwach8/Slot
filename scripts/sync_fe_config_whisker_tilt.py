"""Copy the Whisker Tilt math config into its game client.

Reads  math/whisker_tilt/library/configs/config_fe_whisker_tilt.json (+ math/whisker_tilt/game_config.py)
Writes web-sdk/apps/whisker-tilt/src/game/config.ts
Run with the math-sdk venv after every math run:  math-sdk/env/bin/python scripts/sync_fe_config_whisker_tilt.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "math", "whisker_tilt", "library", "configs", "config_fe_whisker_tilt.json")
DST = os.path.join(ROOT, "web-sdk", "apps", "whisker-tilt", "src", "game", "config.ts")

with open(SRC) as f:
    config = json.load(f)
if isinstance(config.get("symbols"), list):
    config["symbols"] = {k: v for item in config["symbols"] for k, v in item.items()}

MATH_SDK = os.environ.get("MATH_SDK", os.path.join(ROOT, "math-sdk"))
sys.path[:0] = [MATH_SDK, os.path.join(ROOT, "math", "whisker_tilt")]
os.chdir(MATH_SDK)
from game_config import GameConfig, MAX_FREE_SPINS, FREE_RETRIGGER  # noqa: E402

gc = GameConfig()
base = gc.freespin_triggers[gc.basegame_type]
config["providerName"] = gc.provider_name
config["wtRules"] = {
    "minCluster": gc.min_cluster,
    "keyAwards": [{"keys": k, "spins": base[k]} for k in sorted(base) if k < gc.super_trigger],
    "superTrigger": gc.super_trigger,
    "superSpins": gc.super_spins,
    "retriggerKeys": min(gc.freespin_triggers[gc.freegame_type]),
    "retriggerSpins": FREE_RETRIGGER,
    "maxFreeSpins": MAX_FREE_SPINS,
    "superStartKeeper": gc.super_start_keeper,
    "featureStartKeeper": gc.feature_start_keeper,
    "keeperCap": gc.keeper_cap,
    "coinValues": gc.coin_values,
    "mysteryGifts": [{"kind": k, "spins": s, "weight": w} for (k, s), w in gc.mystery_gifts.items()],
    "wincap": gc.wincap,
}

with open(DST, "w") as f:
    f.write("// Generated by scripts/sync_fe_config_whisker_tilt.py from the math SDK output. Do not edit by hand.\n")
    f.write("export default " + json.dumps(config, indent="\t") + ";\n")
print(f"wrote {DST} ({len(config.get('symbols', {}))} symbols, modes: {list(config.get('betModes', {}))})")
